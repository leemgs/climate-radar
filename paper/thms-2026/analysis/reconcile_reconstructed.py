#!/usr/bin/env python3
"""Compare the materials recovered from backup (data/reconstructed/) with the primary study logs (data/).

Run:  python3 -I reconcile_reconstructed.py   (writes ../notes/reconstructed_reconciliation.md)
Nothing here modifies the primary data or any reported number.
"""
from pathlib import Path
import pandas as pd
import openpyxl

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REC = ROOT / "data" / "reconstructed"

rec = pd.read_csv(REC / "ai_recommendation_generation_log.csv")
old = pd.read_csv(ROOT / "data" / "03_trial_logs.csv")
old = old[old.condition == "AI"]
m = old.merge(rec, left_on=["participant", "scenario"], right_on=["participant_id", "scenario"])
assert len(m) == 520
NORM = {"Recommend_Evacuation": "Evacuate", "Shelter_in_Place": "Shelter", "Issue_Alert": "Issue alert", "Monitor": "Monitor", "Standby": "Standby"}
m["sel_old"] = m.selected_action_x.map(NORM); m["ref_old"] = m.correct_action.map(NORM)

wrong = rec[~rec.ai_correct]
wb = openpyxl.load_workbook(REC / "training_checklist_and_records.xlsx", data_only=True)
tr = [r for r in wb["Completion_Records"].iter_rows(min_row=4, values_only=True) if r[0] and str(r[0]).startswith("P")]
dur = pd.Series([r[2] for r in tr]); tries = pd.Series([r[3] for r in tr])

rows = [
    ("Trials (AI-assisted)", len(old), len(rec), "—"),
    ("AER", f"{(old.selected_action==old.correct_action).mean():.3f}", f"{(rec.selected_action==rec.reference_action).mean():.3f}", "similar in aggregate"),
    ("Escalated trials", int((old.escalation=="Yes").sum()), int(rec.escalation_flag.sum()), f"trial-level agreement {((m.escalation=='Yes').astype(int)==m.escalation_flag).mean():.0%}"),
    ("Deferral trials", int((old.deferral=="Yes").sum()), int(rec.deferral_flag.sum()), f"trial-level agreement {((m.deferral=='Yes').astype(int)==m.deferral_flag).mean():.0%}"),
    ("Mean latency (s)", f"{old.response_time_sec.mean():.2f}", f"{rec.latency_s.mean():.2f}", f"identical (±0.05 s) in {(abs(m.response_time_sec-m.latency_s)<0.05).mean():.1%} of trials"),
    ("Same selected action (same participant x scenario)", "", "", f"{(m.sel_old==m.selected_action_y).mean():.1%} (labels normalized to the recovered naming)"),
    ("Same reference action", "", "", f"{(m.ref_old==m.reference_action).mean():.1%} (chance with 5 options is about 20%)"),
    ("Reference actions per scenario ID", "5 distinct", "1 distinct", "primary log: IDs do not map to a reference action"),
]
md = ["# Reconciliation: materials recovered from backup vs. primary study logs\n",
      "Generated by `analysis/reconcile_reconstructed.py`. Provenance of `data/reconstructed/`: re-created or re-organized by the author from backup storage (author statement, 2026-11-20); not original session output.\n",
      "| Item | Primary log (`data/`) | Recovered (`data/reconstructed/`) | Comment |\n|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
md += ["",
 "## Other internal inconsistencies in the recovered files",
 f"- Training records: stated summary \"mean 18.4 min (SD 2.3); 8 participants needed one additional explanation\"; the 52 rows give mean {dur.mean():.1f} min (SD {dur.std():.1f}) and {(tries>3).sum()} participants with more than 3 practice trials.",
 "- Expert file: states \"consensus rate 92% (9/10 scenarios initial agreement after discussion)\"; the table shows 5/10 unanimous (4/4) and 5/10 with 3/4 initial agreement, all resolved by discussion.",
 "- Scenario file: states escalation \"in exactly 150 trials\", but its own per-scenario flags (S03, S06, S08, S10 = 4 scenarios x 52) give 208; the primary log has 150.",
 "- Screenshots: Fig. S1 is dated May 24, 2025, Fig. S3 May 15, 2024; risk is shown as 0.71 (0-1) in S1 and 72 (0-100) in S3; both look like rendered mock-ups.",
 f"- Automation-bias summary (43/104 = 41.3%) reproduces from the recovered log ({int(wrong.followed_ai.sum())}/{len(wrong)}), but that log does not match the primary log at trial level, so the figure is not evidence about the study.",
 "",
 "## Use rule",
 "The recovered materials are cited only as post hoc reconstructions (Supplementary S8). No result in the manuscript is computed from them."]
(ROOT / "notes" / "reconstructed_reconciliation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
